//! Leptos UI for the one-page site. Phase 1: static shell, no interactivity.
//!
//! Layout follows the site plan: hero (one-liner + install), the XX device
//! preview (the static final-state of what phase 2 animates), the proof
//! strip, and the install footer. Copy is lifted from the README — the page
//! asserts nothing the crate's docs don't.

use leptos::prelude::*;

/// The Quickstart's XX declaration, verbatim from the README. Rendered after
/// a cyan `hiss::noise!` span, so the string starts at the brace.
const NOISE_XX_BODY: &str = r#" {
    pub XX<X25519, ChaChaPoly, Blake2b> {
        -> e
        <- e, ee, s, es
        -> s, se
    }
}"#;

