//! Blocking `std::io` handshake adapter.
//!
//! A synchronous, [`std::io::Read`]/[`std::io::Write`] surface over the
//! type-state Noise handshake — the caller
//! hands the handshake a stream and drives it with a fluent token chain
//! that reads/writes the wire directly, no `.await`, no caller-sized
//! buffer:
//!
//! ```ignore
//! use hiss::noise::*;
//!
//! // Pin the protocol locally; the `sync_initiator`/`sync_responder`
//! // constructors fix the role, so there is no
//! // `SyncHandshake::<…, …, _, _, _, _>` turbofish.
//! type Channel = Noise<pattern::N, P256, ChaChaPoly, Blake2b>;
//!
//! // initiator — `stream: impl std::io::Write`
//! let i = Channel::sync_initiator(provider, &[], stream)
//!     .set_rs(recipient_pub);
//! let mut sealed = i.e()?.es()?;          // msg1 streamed to the wire; `sealed` owns the stream
//!
//! // responder — `stream: impl std::io::Read`
//! let r = Channel::sync_responder(provider, &[], stream)
//!     .set_s(recipient_static)?;
//! let (their_e, recv) = r.recv().e()?;    // each token reads exactly its bytes off the wire
//! let mut opened = recv.es()?;
//! ```
//!
//! # Design
//!
//! This is one of the two handshake drivers (the other is the async
//! `AsyncHandshake`, feature `async-io`). Each token
//! method threads its compile-time-sized bytes through a small fixed
//! stack scratch and streams them to the stream, so the bytes on the
//! wire are byte-identical to the async path; only the I/O differs. The
//! structure is three `impl` blocks per token per context (more-tokens /
//! last-token-more-messages / last-token-last-message), generated by
//! macros.
//!
//! # Synchronous crypto
//!
//! The blocking handshake is generic over [`DhProvider`] — the
//! synchronous provider surface — and calls its methods directly (no
//! executor, no future-polling). Both backends implement it: software
//! (`eccoxide`) natively, and Apple **Secure Enclave** (whose
//! Security-framework calls are synchronous, blocking C functions) by
//! running them on the calling thread — exactly as Apple's libraries
//! expose them. An async-only provider cannot be used here: it is a
//! *compile* error (it does not implement [`DhProvider`]).
//!
//! The provider-free token helpers (`recv_e`/`recv_s`/`send_s`/
//! `send_payload`/`recv_payload`/`do_psk`/`recv_to_transport`) are shared
//! with the async driver via the internal `process` module; only the
//! DH/ephemeral steps that call the provider have synchronous mirrors
//! here.
//!
//! # Flushing & cancellation
//!
//! Each completed outgoing handshake message is flushed before the call
//! returns, so it reaches the peer even over a buffered writer (and a
//! multi-message handshake does not deadlock waiting on unflushed bytes).
//! Bytes are streamed per token and crypto state advances as they are
//! produced, so a mid-handshake I/O error is **fatal and unrecoverable**
//! — drop the whole handshake and the connection; there is no per-token
//! retry (the same contract as `tokio-rustls`).
//!
//! # Timeouts
//!
//! The handshake read path has **no clock**: a `recv` token blocks until
//! its bytes arrive, so a stalling or silent peer can hang the call
//! indefinitely. Impose a timeout yourself — typically a read timeout on
//! the underlying socket (e.g. [`TcpStream::set_read_timeout`](std::net::TcpStream::set_read_timeout)).

