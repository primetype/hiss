//! Noise handshake state machine.
//!
//! The three state types — [`HandshakeState`], [`Sending`], and
//! [`Receiving`] — form a type-state machine driven by the Cons-list
//! token sequence from the [`Pattern`] trait.
//!
//! * [`HandshakeState`] sits *between* messages. Its only operations
//!   are starting the next send or receive message, or finishing the
//!   handshake when all messages have been processed.
//!
//! * [`Sending`] and [`Receiving`] sit *within* a message. Each
//!   token method (`.e()`, `.es()`, etc.) advances the token
//!   Cons-list by one step. The return type changes depending on
//!   whether more tokens remain, more messages remain, or the
//!   handshake is complete.

use super::Protocol;
use super::buffers::{RecvBuffer, SendBuffer};
use super::cipher::Cipher;
