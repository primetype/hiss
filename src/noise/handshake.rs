// ── Transitions: HandshakeState → Sending / Receiving ─────────

// Start a send message (when next message direction = our SendDir).
// Only available once all pre-messages have been processed (PreMsgs = Nil).
impl<N, R, Dir, Tokens, Rest, CP> HandshakeState<N, R, Nil, Cons<Message<Dir, Tokens>, Rest>, CP>
where
    N: Protocol,
    R: Role<SendDir = Dir>,
    CP: CryptoProviderAsync<N::Curve>,
    Tokens: WireSize<N::Curve, N::Cipher, true> + WireSize<N::Curve, N::Cipher, false>,
{
    /// Begin sending the next handshake message into the provided
    /// output buffer.
    ///
    /// The buffer must be exactly the right size for this message.
    /// Use [`noise_message_size!`](crate::noise_message_size) to compute the size at compile
    /// time, or [`expected_send_size`](Self::expected_send_size) to query it at runtime.
    ///
    /// This is called implicitly by the first token method — users
    /// do not need to call this directly. It transitions from
    /// [`HandshakeState`] to [`Sending`].
    pub(crate) fn begin_send(self, output: &mut [u8]) -> Sending<'_, N, R, Tokens, Rest, CP> {
        Sending {
            inner: self.inner,
            buffer: SendBuffer::new(output),
            _marker: PhantomData,
        }
    }

    /// Returns the exact number of bytes needed for the next
    /// outgoing message.
    pub fn expected_send_size(&self) -> usize {
        wire_size::<N::Curve, N::Cipher, Tokens>(self.inner.has_psk, self.inner.symmetric.has_key())
    }
}

// Start a receive message (when next message direction = our RecvDir).
// Only available once all pre-messages have been processed (PreMsgs = Nil).
impl<N, R, Dir, Tokens, Rest, CP> HandshakeState<N, R, Nil, Cons<Message<Dir, Tokens>, Rest>, CP>
where
    N: Protocol,
    R: Role<RecvDir = Dir>,
    CP: CryptoProviderAsync<N::Curve>,
    Tokens: WireSize<N::Curve, N::Cipher, true> + WireSize<N::Curve, N::Cipher, false>,
{
    /// Begin reading an incoming handshake message.
    ///
    /// Borrows the incoming message directly — no copy. Validates
    /// that the message length matches the expected wire size.
    ///
    /// Returns [`HandshakeError::UnexpectedMessageLength`] if the
    /// message length does not match the expected size.
    pub fn read<'a>(
        self,
        message: &'a [u8],
    ) -> Result<Receiving<'a, N, R, Tokens, Rest, CP>, HandshakeError> {
        let expected = wire_size::<N::Curve, N::Cipher, Tokens>(
            self.inner.has_psk,
            self.inner.symmetric.has_key(),
        );
        if message.len() != expected {
            return Err(HandshakeError::UnexpectedMessageLength {
                expected,
                actual: message.len(),
            });
        }
        Ok(Receiving {
            inner: self.inner,
            buffer: RecvBuffer::new(message),
            _marker: PhantomData,
        })
    }

    /// Returns the exact number of bytes expected for the next
    /// incoming message, computed at compile time from the token list.
    pub fn expected_message_size(&self) -> usize {
        wire_size::<N::Curve, N::Cipher, Tokens>(self.inner.has_psk, self.inner.symmetric.has_key())
    }
}

// ── Sending — within a send message ───────────────────────────

/// State within a send message.
///
/// Each token method appends data to the borrowed output buffer and
/// advances the token Cons-list. The return type depends on the
/// remaining tokens and messages.
pub struct Sending<'a, N, R, Tokens, MsgRest, CP>
where
    N: Protocol,
    CP: CryptoProviderAsync<N::Curve>,
{
    pub(crate) inner: HandshakeInner<N::Curve, N::Cipher, N::Hash, CP>,
    pub(crate) buffer: SendBuffer<'a>,
    pub(crate) _marker: PhantomData<fn() -> (N, R, Tokens, MsgRest)>,
}

// ── Receiving — within a receive message ──────────────────────

/// State within a receive message.
///
/// Each token method reads data from the borrowed input buffer and
/// advances the token Cons-list. The return type depends on the
/// remaining tokens and messages. No copy — the incoming message
/// bytes are read directly.
pub struct Receiving<'a, N, R, Tokens, MsgRest, CP>
where
    N: Protocol,
    CP: CryptoProviderAsync<N::Curve>,
{
    pub(crate) inner: HandshakeInner<N::Curve, N::Cipher, N::Hash, CP>,
    pub(crate) buffer: RecvBuffer<'a>,
    pub(crate) _marker: PhantomData<fn() -> (N, R, Tokens, MsgRest)>,
}
