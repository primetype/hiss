impl<N, CP, Io>
    AsyncHandshake<
        N,
        Initiator,
        <N::Pattern as Pattern>::PreMessages,
        <N::Pattern as Pattern>::Messages,
        CP,
        Io,
    >
where
    N: Protocol,
    CP: CryptoProviderAsync<N::Curve>,
{
    /// Begin an async handshake as the **initiator** over `stream`.
    pub fn initiate(provider: CP, prologue: &[u8], stream: Io) -> Self {
        let core = HandshakeState::<
            N,
            Initiator,
            <N::Pattern as Pattern>::PreMessages,
            <N::Pattern as Pattern>::Messages,
            CP,
        >::new(provider, prologue);
        AsyncHandshake {
            inner: core.inner,
            stream,
            _marker: PhantomData,
        }
    }
}

impl<N, CP, Io>
    AsyncHandshake<
        N,
        Responder,
        <N::Pattern as Pattern>::PreMessages,
        <N::Pattern as Pattern>::Messages,
        CP,
        Io,
    >
where
    N: Protocol,
    CP: CryptoProviderAsync<N::Curve>,
{
    /// Begin an async handshake as the **responder** over `stream`.
    pub fn respond(provider: CP, prologue: &[u8], stream: Io) -> Self {
        let core = HandshakeState::<
            N,
            Responder,
            <N::Pattern as Pattern>::PreMessages,
            <N::Pattern as Pattern>::Messages,
            CP,
        >::new(provider, prologue);
        AsyncHandshake {
            inner: core.inner,
            stream,
            _marker: PhantomData,
        }
    }
}

