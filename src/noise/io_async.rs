// ═══════════════════════════════════════════════════════════════
//  Macro: three-variant impls for a send token
// ═══════════════════════════════════════════════════════════════

/// Generate three `impl` blocks for a send-side token method. The body
/// has access to `inner: &mut HandshakeInner` and `stream: &mut Io`
/// (name it `_stream` for DH/psk tokens that write nothing) plus any
/// declared args.
macro_rules! async_send_token {
    (
        role: $R:ty,
        token: $Token:ty,
        method: $method:ident ($($arg:ident : $arg_ty:ty),*),
        bounds: [$($extra:tt)*],
        body: |$inner:ident, $stream:ident| { $($logic:tt)* }
    ) => {
        // Variant 1: more tokens after this one.
        impl<N, Next, More, MsgRest, CP, Io>
            AsyncSending<N, $R, Cons<$Token, Cons<Next, More>>, MsgRest, CP, Io>
        where
            N: Protocol,
            <N::Curve as Curve>::PublicKey: AsRef<[u8]>,
            CP: CryptoProviderAsync<N::Curve>,
            Io: AsyncWrite + Unpin,
            $($extra)*
        {
            pub async fn $method(
                mut self, $($arg: $arg_ty,)*
            ) -> Result<AsyncSending<N, $R, Cons<Next, More>, MsgRest, CP, Io>, HandshakeError> {
                {
                    let $inner = &mut self.inner;
                    let $stream = &mut self.stream;
                    $($logic)*
                }
                Ok(AsyncSending { inner: self.inner, stream: self.stream, _marker: PhantomData })
            }
        }

        // Variant 2: last token, more messages.
        impl<N, NextMsg, MoreMsgs, CP, Io>
            AsyncSending<N, $R, Cons<$Token, Nil>, Cons<NextMsg, MoreMsgs>, CP, Io>
        where
            N: Protocol,
            <N::Curve as Curve>::PublicKey: AsRef<[u8]>,
            CP: CryptoProviderAsync<N::Curve>,
            Io: AsyncWrite + Unpin,
            $($extra)*
        {
            pub async fn $method(
                mut self, $($arg: $arg_ty,)*
            ) -> Result<AsyncHandshake<N, $R, Nil, Cons<NextMsg, MoreMsgs>, CP, Io>, HandshakeError> {
                {
                    let $inner = &mut self.inner;
                    let $stream = &mut self.stream;
                    $($logic)*
                }
                send_message_tail_async(&mut self.inner, &mut self.stream).await?;
                Ok(AsyncHandshake { inner: self.inner, stream: self.stream, _marker: PhantomData })
            }
        }

        // Variant 3: last token, last message.
        impl<N, CP, Io>
            AsyncSending<N, $R, Cons<$Token, Nil>, Nil, CP, Io>
        where
            N: Protocol,
            <N::Curve as Curve>::PublicKey: AsRef<[u8]>,
            CP: CryptoProviderAsync<N::Curve>,
            Io: AsyncWrite + Unpin,
            $($extra)*
        {
            pub async fn $method(
                mut self, $($arg: $arg_ty,)*
            ) -> Result<AsyncTransport<N, Io>, HandshakeError> {
                {
                    let $inner = &mut self.inner;
                    let $stream = &mut self.stream;
                    $($logic)*
                }
                send_message_tail_async(&mut self.inner, &mut self.stream).await?;
                let transport = recv_to_transport::<N, $R, CP>(self.inner);
                Ok(AsyncTransport { transport, stream: self.stream })
            }
        }
    };
}

