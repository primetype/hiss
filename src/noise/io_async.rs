//! Asynchronous `tokio::io` handshake adapter (feature `async-io`).
//!
//! The async mirror of [`io_sync`](super::io_sync): a
//! [`tokio::io::AsyncRead`]/[`tokio::io::AsyncWrite`] surface over the
//! same type-state Noise handshake as the buffer core. The caller hands
//! the handshake a stream and drives it with a fluent token chain that
//! `.await`s reads/writes on the wire directly, with no caller-sized
//! buffer:
//!
//! ```ignore
//! use hiss::noise::*;
//! type Seal = Noise<N, P256, ChaChaPoly, Blake2b>;
//!
//! // initiator — `stream: impl tokio::io::AsyncWrite + Unpin`
//! let i = AsyncHandshake::<Seal, Initiator, _, _, _, _>::initiate(provider, &[], stream)
//!     .set_rs(recipient_pub);
//! let mut sealed = i.e().await?.es().await?;   // msg1 streamed + flushed; `sealed` owns the stream
//!
//! // responder — `stream: impl tokio::io::AsyncRead + Unpin`
//! let r = AsyncHandshake::<Seal, Responder, _, _, _, _>::respond(provider, &[], stream)
//!     .set_s(recipient_static)?;
//! let (their_e, recv) = r.recv().e().await?;   // each token reads exactly its bytes off the wire
//! let mut opened = recv.es().await?;
//! ```
//!
//! # Design
//!
//! This layer is **purely additive**: the buffer-based core
//! ([`HandshakeState`]/[`Sending`]/[`Receiving`](super::handshake)) is
//! untouched and remains canonical, and so is the blocking
//! [`io_sync`](super::io_sync) layer. Each token method here threads its
//! compile-time [`WireSize`](super::tokens::WireSize)-sized bytes through
//! a small fixed stack scratch and streams them to the stream, so the
//! bytes on the wire are identical to both other paths; only buffer
//! ownership and the I/O differ. The structure mirrors
//! [`io_sync`](super::io_sync): three `impl` blocks per token per context,
//! generated by macros.
//!
//! The per-token crypto is shared verbatim with the buffer core — the
//! `async` token helpers in [`process`](super::process) are reused
//! directly, so there is a single source of truth for the Noise mix
//! sequence.
//!
//! # Asynchronous crypto
//!
//! The handshake is generic over [`CryptoProviderAsync`] — the
//! async provider surface — and `.await`s its operations. Both backends
//! implement it: software (`eccoxide`) resolves immediately, and Apple
//! **Secure Enclave** offloads its blocking Security-framework calls to
//! a worker thread (`tokio::task::spawn_blocking`) so the executor never
//! blocks. A sync-only provider that does not implement
//! [`CryptoProviderAsync`] is a *compile* error here.
//!
//! # Flushing & cancellation
//!
//! Each completed outgoing handshake message is flushed before the call
//! returns, so it reaches the peer even over a buffered stream (the
//! `tokio-rustls` contract). Bytes are streamed per token and crypto
//! state advances as they are produced, so dropping a handshake future
//! mid-message — or a mid-handshake I/O error — is **fatal and
//! unrecoverable**: drop the whole handshake and the connection; there
//! is no per-token retry.

